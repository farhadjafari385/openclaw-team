def disable_crons(team):
    jobs = _cron_jobs(team)
    if jobs is None:
        return ["could not list crons (is the gateway up?)"]
    wanted = set(team.get("crons", {}).get("disabled", []))
    done = []
    for job in jobs or []:
        if isinstance(job, dict) and (job.get("name") in wanted) and job.get("enabled", True):
            run([openclaw(team), "cron", "disable", job["id"]], timeout=120)
            done.append(job.get("name"))
    return done


def _cron_jobs(team):
    r = run([openclaw(team), "cron", "list", "--json"], timeout=200)
    out = r.stdout
    starts = [i for i in (out.find("{"), out.find("[")) if i >= 0]
    if not starts:
        return None
    try:
        data = json.loads(out[min(starts):])
    except Exception:
        return None
    return data.get("jobs", []) if isinstance(data, dict) else data


def crons_still_enabled(team):
    data = _cron_jobs(team)
    if data is None:
        return None
    wanted = set(team.get("crons", {}).get("disabled", []))
    return [j.get("name") for j in data if isinstance(j, dict) and j.get("name") in wanted and j.get("enabled", True)]


