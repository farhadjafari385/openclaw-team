def gc_candidates(rows, now_ms, finished_minutes=30, idle_hours=24, everything=False):
    """Sessions to delete: finished task sessions after `finished_minutes`, anything else idle for `idle_hours`.
    Running sessions are never touched."""
    out = []
    for r in rows:
        key = r.get("key") or ""
        if not key or str(r.get("status") or "").lower() in ("running", "active", "busy"):
            continue
        if everything:
            out.append(r)
            continue
        updated = r.get("updatedAt") or (now_ms - r["ageMs"] if isinstance(r.get("ageMs"), (int, float)) else None)
        if not isinstance(updated, (int, float)):
            continue
        idle_ms = now_ms - updated
        if ":subagent:" in key:
            if idle_ms >= finished_minutes * 60000:
                out.append(r)
        elif idle_ms >= idle_hours * 3600000:
            out.append(r)
    return out


