def expand(p):
    return Path(os.path.expanduser(str(p)))


def sha(text):
    data = text if isinstance(text, bytes) else text.encode()
    return hashlib.sha256(data).hexdigest()


def read(path):
    """A file's text; a team file from this repo has its {{private:KEY}} placeholders filled (see fill)."""
    text = Path(path).read_text()
    return fill(text, path) if is_team_file(path) else text


# ---------------------------------------------------------------- private values
# The repo is public-safe: owner ids, hosts, paths, bot names and brands live in a private.toml that is never
# committed. Team files hold {{private:KEY}} placeholders; read() fills them, so every rendered file and config
# is exactly what it was with the values inline. A missing file or key is refused, never rendered half-filled.

PRIVATE_RE = re.compile(r"\{\{private:([A-Za-z0-9_]+)\}\}")
PRIVATE_EXAMPLE = REPO / "private.example.toml"
_private_cache = {}


def is_team_file(path):
    try:
        rel = Path(path).resolve().relative_to(REPO)
    except ValueError:
        return False
    return rel.parts[:1] != ("vendor-skills",)


def private_file():
    """Where the private values are: $OPENCLAW_TEAM_PRIVATE, else private.toml in the repo (the laptop), else
    ~/.config/openclaw-team/private.toml (the host: a deploy replaces the checkout, this file stays)."""
    env = os.environ.get("OPENCLAW_TEAM_PRIVATE")
    if env:
        return Path(env).expanduser()
    for p in (REPO / "private.toml", HOME / ".config" / "openclaw-team" / "private.toml"):
        if p.exists():
            return p
    return None


def private_values():
    p = private_file()
    if p is None:
        raise SystemExit("private.toml not found: copy private.example.toml to private.toml (repo root, or "
                         "~/.config/openclaw-team/private.toml on the host) and fill in the real values")
    key = (str(p), p.stat().st_mtime_ns if p.exists() else 0)
    if key not in _private_cache:
        try:
            values = tomllib.loads(p.read_text()).get("values", {})
        except (OSError, tomllib.TOMLDecodeError) as e:
            raise SystemExit(f"{p}: cannot read the private values ({e})")
        _private_cache.clear()
        _private_cache[key] = {k: str(v) for k, v in values.items()}
    return _private_cache[key]


def fill(text, where="text"):
    """Replace every {{private:KEY}}; refuse (naming each missing key) if any has no value."""
    if "{{private:" not in text:
        return text
    values = private_values()
    missing = sorted({k for k in PRIVATE_RE.findall(text) if k not in values})
    if missing:
        raise SystemExit(f"{where}: no private value for {', '.join(missing)} (add them to {private_file()} under [values])")
    out = PRIVATE_RE.sub(lambda m: values[m.group(1)], text)
    if "{{private:" in out:
        raise SystemExit(f"{where}: a malformed {{{{private:...}}}} placeholder is left after filling")
    return out


def private_leaks(paths, values=None):
    """[(path, key)] for every private value found verbatim in the given files (the public-repo guard)."""
    values = private_values() if values is None else values
    needles = [(k, v) for k, v in values.items() if len(v) >= 4]
    out = []
    for p in paths:
        try:
            text = Path(p).read_text(errors="replace")
        except (OSError, IsADirectoryError):
            continue
        out += [(str(p), k) for k, v in needles if v in text]
    return out


