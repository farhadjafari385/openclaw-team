def usage_by_agent(hours=24):
    since = datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(hours=hours)
    out = {}
    for f in glob.glob(str(HOME / ".claude" / "projects" / "*" / "*.jsonl")):
        if os.path.getmtime(f) < since.timestamp():
            continue
        m = re.search(r"openclaw-workspace-([a-z]+)", os.path.dirname(f))
        agent = m.group(1) if m else "other"
        a = out.setdefault(agent, {"turns": 0, "read": 0, "write": 0, "out": 0, "sessions": set()})
        for line in open(f, errors="replace"):
            try:
                e = json.loads(line)
            except Exception:
                continue
            if e.get("type") != "assistant":
                continue
            ts = e.get("timestamp", "")
            try:
                if datetime.datetime.fromisoformat(ts.replace("Z", "+00:00")) < since:
                    continue
            except Exception:
                continue
            u = (e.get("message") or {}).get("usage") or {}
            if not u:
                continue
            a["turns"] += 1
            a["read"] += (u.get("input_tokens") or 0) + (u.get("cache_read_input_tokens") or 0)
            a["write"] += u.get("cache_creation_input_tokens") or 0
            a["out"] += u.get("output_tokens") or 0
            a["sessions"].add(os.path.basename(f))
    return out


