EXACT_SUBTREES = {"tools", "model", "subagents", "identity", "config", "servers"}


def pick(live, desired):
    """The part of `live` that `desired` manages."""
    if not isinstance(desired, dict) or not isinstance(live, dict):
        return live
    return {k: pick(live.get(k), v) if isinstance(v, dict) else live.get(k) for k, v in desired.items()}


def build_patch(live, desired, path=(), exact_parent=False):
    """Merge patch turning the managed part of `live` into `desired`; exact subtrees (and every dict inside
    them) also drop extra keys, so a setting removed from the repo is removed from the host too."""
    patch = {}
    live = live if isinstance(live, dict) else {}
    for k, v in desired.items():
        lv = live.get(k)
        if isinstance(v, dict):
            exact = exact_parent or (k in EXACT_SUBTREES and not (k == "config" and (not path or path[-1] != "token-guard")))
            if exact and isinstance(lv, dict):
                sub = build_patch(lv, v, path + (k,), True)
                for extra in set(lv) - set(v):
                    sub[extra] = None
            else:
                sub = build_patch(lv if isinstance(lv, dict) else {}, v, path + (k,))
            if sub or not isinstance(lv, dict):
                patch[k] = sub if isinstance(lv, dict) else v
        elif lv != v:
            patch[k] = v
    return patch


