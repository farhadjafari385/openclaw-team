def drift_restorable(drifted, files, applied):
    """(restore, held): drift restores a file only to the version last applied. A newer repo
    version is deployed by `team apply`, never by drift (on 2026-11-04 a drift run between a
    repo update and its apply deployed it and posted "Drift restored")."""
    applied_files = (applied or {}).get("files") or {}
    if not applied_files:
        return list(drifted), []
    restore = [p for p in drifted if applied_files.get(p) == sha(files[p])]
    return restore, [p for p in drifted if p not in restore]


