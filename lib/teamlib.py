# ---------------------------------------------------------------- startup quiet window
# On this host a gateway start takes 5-10 minutes, and heavy work beside it makes OpenClaw give up on an agent: a
# database step times out and the agent is locked until the next restart, or the reply runtime is never published.
# On 2026-11-11 the hourly session clean-up (one `openclaw sessions delete` process per 5 sessions, each writing the
# same databases), the disk janitor and the code maps ran beside three restarts. The team's own timers now leave the
# first STARTUP_QUIET_MIN minutes after any start to the gateway, whoever restarted it.
# On 2026-11-12 a deploy's apply started these timers while the gateway was stopped: no age, so no start to wait
# out, and the session clean-up (12 CPU minutes) and code maps (8.5) ran through the whole start, which took 15
# minutes before the orchestrator answered. A stopped gateway is about to start (Restart=always, a deploy, a heal),
# and the maintenance flag means a restart is under way: both count as the start.
STARTUP_QUIET_MIN = 20
MAINTENANCE_FLAG = Path.home() / ".openclaw" / "token-guard-state" / "maintenance"
FLAG_HOLD_MIN = 30  # the guard honours the flag this long after its last touch


def gateway_age_s():
    """Seconds since the gateway's main process started; None when it is not running."""
    pid = subprocess.run(["systemctl", "--user", "show", "-p", "MainPID", "--value", "openclaw-gateway"], capture_output=True, text=True).stdout.strip()
    if not pid or pid == "0":
        return None
    out = subprocess.run(["ps", "-o", "etimes=", "-p", pid], capture_output=True, text=True).stdout.strip()
    return int(out) if out.isdigit() else None


def in_startup_window(age_s, minutes=STARTUP_QUIET_MIN):
    return age_s is None or age_s < minutes * 60


def restart_under_way(flag=None, now=None):
    f = Path(flag or MAINTENANCE_FLAG)
    try:
        return (now or time.time()) - f.stat().st_mtime < FLAG_HOLD_MIN * 60
    except OSError:
        return False


def skip_during_startup(name, age_s=None):
    age = gateway_age_s() if age_s is None else age_s
    if age is None:
        why = "the gateway is not running: its start comes next"
    elif age < STARTUP_QUIET_MIN * 60:
        why = f"the gateway started {age // 60} min ago"
    elif restart_under_way():
        why = "a restart is under way (maintenance flag)"
    else:
        return False
    print(f"{name}: skipped, {why} (it gets the first {STARTUP_QUIET_MIN} minutes of a start to itself)")
    return True


def startup_failures_check(stability_dir=None, now=None, window_min=30):
    """A failed gateway start leaves a stability bundle. On 2026-11-14 three starts in a row failed and OpenClaw
    restarted itself in-process each time (systemd saw one start); verify ran between two of them and said 120/120."""
    d = Path(stability_dir or HOME / ".openclaw" / "logs" / "stability")
    now = now or time.time()
    recent = sorted((f for f in d.glob("*startup_failed.json") if now - f.stat().st_mtime < window_min * 60), key=lambda f: f.stat().st_mtime)
    msg = f"no failed gateway start in the last {window_min} min"
    return (not recent, msg if not recent else f"{len(recent)} failed gateway start(s) in the last {window_min} min, latest {recent[-1].name}")


# ---------------------------------------------------------------- Telegram message cache
# OpenClaw keeps every Telegram message the bots see in "@retained.telegram.message-cache" with no expiry (22,053
# entries, 32.6 MB on 2026-11-14, back to 2026-10-24), and loads the whole namespace on the gateway's main thread to
# fill each bot's cache. The gateway's event loop had stalled for 12 s typically and up to 327 s for days, and starts
# took longer and longer. apply trims it to [limits] telegram_cache_keep_days while the gateway is stopped; what it
# removes is kept as gzipped JSON lines in the apply backup.
TELEGRAM_RETAINED_NS = "@retained.telegram.message-cache"


def prune_telegram_cache(db_path, keep_days, backup_dir, now_ms=None):
    import gzip
    import sqlite3
    now_ms = now_ms or int(time.time() * 1000)
    cut = now_ms - int(keep_days) * 86400000
    con = sqlite3.connect(str(db_path), timeout=60)
    try:
        q = "from plugin_state_entries where namespace = ? and created_at < ?"
        rows = con.execute("select plugin_id, namespace, entry_key, value_json, created_at, expires_at " + q, (TELEGRAM_RETAINED_NS, cut)).fetchall()
        if rows:
            Path(backup_dir).mkdir(parents=True, exist_ok=True)
            with gzip.open(Path(backup_dir) / "telegram-retained-cache.jsonl.gz", "wt") as f:
                for r in rows:
                    f.write(json.dumps(dict(zip(("plugin_id", "namespace", "entry_key", "value_json", "created_at", "expires_at"), r))) + "\n")
            con.execute("delete " + q, (TELEGRAM_RETAINED_NS, cut))
            con.commit()
    finally:
        con.close()
    return len(rows)


# ---------------------------------------------------------------- OpenClaw browser timeouts
# OpenClaw (2026.10.5, still in 2026.11.3) hard-codes the remote-browser (CDP) timeouts and ignores config: 1.5 s for
# each HTTP call (open a tab, reachability) and 3 s for the WebSocket handshake. The laptop Team Chrome answers through
# its tunnel in 0.6-3 s (measured 2026-11-11), so opening a tab failed and growth's browser work stopped. apply sets
# both constants to [limits] remote_browser_timeout_ms; verify shows it when an OpenClaw update resets or moves them.
CDP_CONSTS = ("DEFAULT_BROWSER_REMOTE_CDP_TIMEOUT_MS", "DEFAULT_BROWSER_REMOTE_CDP_HANDSHAKE_TIMEOUT_MS")


def openclaw_dist():
    found = sorted(glob.glob(str(HOME / ".openclaw" / "tools" / "node-*" / "lib" / "node_modules" / "openclaw" / "dist")))
    return Path(found[-1]) if found else None


# The Playwright attach behind snapshot, click and navigate (connectOverCDP) has its own timeout per try: 5 s, 7 s,
# 9 s (pw-tools-core.interactions.navigation-*.mjs, `const timeout = 5e3 + attempt * 2e3;`), whatever timeoutMs the
# agent passes. The laptop Team Chrome attaches through its tunnel in 6.1-9.8 s (measured 2026-11-14), so opening a
# tab worked while every page action timed out, and five board items waited on it. apply sets the first try to
# [limits] remote_browser_attach_ms and adds half of that per retry.
ATTACH_RE = r"const timeout = [0-9.e]+ \+ attempt \* [0-9.e]+;"


def attach_line(ms):
    return f"const timeout = {int(ms)} + attempt * {int(ms) // 2};"


def browser_timeout_files(dist):
    if not dist or not Path(dist).is_dir():
        return []
    r = subprocess.run(["grep", "-rlE", "--include=*.mjs", "-e", f"const {CDP_CONSTS[0]} =", "-e", ATTACH_RE, str(dist)],
                       capture_output=True, text=True)
    return sorted(r.stdout.split())


def _browser_patched(s, ms, attach_ms):
    for name in CDP_CONSTS:
        s = re.sub(rf"(const {name} = )[0-9.e]+;", rf"\g<1>{int(ms)};", s)
    if attach_ms:
        s = re.sub(ATTACH_RE, attach_line(attach_ms), s)
    return s


def patch_browser_timeouts(dist, ms, backup_dir=None, attach_ms=0):
    """Sets both constants to `ms` and the attach timeout to `attach_ms` (0: left alone).
    Returns (files changed, files holding them)."""
    files, changed = browser_timeout_files(dist), []
    for f in files:
        s = read(f)
        new = _browser_patched(s, ms, attach_ms)
        if new == s:
            continue
        if backup_dir:
            Path(backup_dir).mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, Path(backup_dir) / os.path.basename(f))
        mode = os.stat(f).st_mode
        tmp = f + ".team-tmp"
        Path(tmp).write_text(new)
        os.chmod(tmp, mode)
        os.replace(tmp, f)
        changed.append(f)
    return changed, files


