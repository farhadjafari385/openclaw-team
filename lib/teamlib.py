def can_lock(team):
    return bool(team["team"].get("lock_files")) and subprocess.run(["sudo", "-n", "true"], capture_output=True).returncode == 0


def chattr(flag, paths):
    paths = [p for p in paths if os.path.exists(p)]
    for i in range(0, len(paths), 200):
        subprocess.run(["sudo", "-n", "chattr", flag, *paths[i:i + 200]], capture_output=True)


def write_files(files, lock):
    changed = [p for p, c in files.items() if not os.path.exists(p) or read(p) != c]
    if lock:
        chattr("-i", changed)
    for p in changed:
        os.makedirs(os.path.dirname(p), exist_ok=True)
        tmp = f"{p}.team-tmp"
        Path(tmp).write_text(files[p])
        os.replace(tmp, p)
    if lock:
        chattr("+i", list(files))
    return changed


