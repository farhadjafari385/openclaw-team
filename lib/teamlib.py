# A long-lived Claude CLI process is kept per session only while its system prompt stays the same
# (cli-live-session-registry: systemPromptHash, extraSystemPromptHash, promptToolNamesHash, argv). OpenClaw built the
# orchestrator's prompt differently for each kind of wake, and these alternate all day in one conversation:
#  - the owner's messages and agents' messages carry a "## Conversation Context" section, guard wakes do not;
#  - the Control UI adds web-chat sections (UI Presentation, Control UI Embed/Side Chat, Collapsible Details), a
#    channel=webchat Runtime line and an inline-buttons line.
# Each change started a new process and the whole conversation was written to the cache again (~54k tokens at Opus
# prices each time). With [limits] cli_stable_system_prompt apply patches prepare.runtime-*.mjs so that
#  1. those per-run sections go into the turn's own context (OpenClaw's runtime-facts-in-turn path), not the system
#     prompt: the model still reads every word, on the turn it applies to;
#  2. the moved sections no longer count as a system-prompt change (extraSystemPromptHash).
# On the orchestrator's real prompts of 2026-11-17 this makes a guard wake, a Telegram message and a web-chat message
# produce the same system prompt. Not covered: a worker's result runs with OpenClaw's tool server and without the
# owner-level tools its worker may not use (gateway, openclaw, plugins, nodes, automations, conversations_*, screen),
# so its tool list still differs; that is a safety limit, not a prompt detail, and is left as OpenClaw has it.
STABLE_MARK = "/* openclaw-team:stable-prompt */"
STABLE_HELPERS = STABLE_MARK + r"""
const TEAM_PER_RUN_SECTIONS = new Set(["## UI Presentation", "## Control UI Embed", "## Control UI Side Chat", "## Collapsible Details", "## Reactions"]);
function teamStableSystemPrompt(prompt, split, splitRelocatable) {
	const base = split ?? splitRelocatable(prompt) ?? { remainingPrompt: prompt, relocatable: void 0 };
	const keep = [], moved = [];
	let moving = false, inContext = false;
	for (const line of base.remainingPrompt.split("\n")) {
		if (line.startsWith("## ")) {
			const heading = line.trimEnd();
			if (heading === "## Conversation Context" || heading === "## Subagent Context") inContext = moving = true;
			else if (inContext && heading !== "## Runtime") moving = true;
			else {
				inContext = false;
				moving = TEAM_PER_RUN_SECTIONS.has(heading);
			}
		} else if (!moving && line.startsWith("- Inline buttons OFF for ")) {
			moved.push(line);
			continue;
		}
		(moving ? moved : keep).push(line);
	}
	const relocatable = [base.relocatable, moved.join("\n").trim()].filter((value) => Boolean(value?.trim())).join("\n\n");
	return {
		remainingPrompt: keep.join("\n").trimEnd(),
		relocatable: relocatable || void 0
	};
}
"""
STABLE_EDITS = [
    ("function resolveCliRuntimeToolPolicy(input) {",
     STABLE_HELPERS + "function resolveCliRuntimeToolPolicy(input) {"),
    ("const baseExtraSystemPromptHash = bindingExtraSystemPromptStatic !== void 0 ? hashCliSessionText(bindingExtraSystemPromptStatic.trim() || void 0) : hashCliSessionText(extraSystemPrompt);",
     "const baseExtraSystemPromptHash = !skipsTurnPreparation ? void 0 : bindingExtraSystemPromptStatic !== void 0 ? hashCliSessionText(bindingExtraSystemPromptStatic.trim() || void 0) : hashCliSessionText(extraSystemPrompt);"),
    ("const turnRuntimeFacts = params.runtimeFactsInTurn && !skipsTurnPreparation ? splitSystemPromptRelocatableBoundary(transformedSystemPrompt) : void 0;",
     "const turnRuntimeFacts = !skipsTurnPreparation ? teamStableSystemPrompt(transformedSystemPrompt, params.runtimeFactsInTurn ? splitSystemPromptRelocatableBoundary(transformedSystemPrompt) : void 0, splitSystemPromptRelocatableBoundary) : void 0;"),
]


def stable_prompt_files(dist):
    if not dist or not Path(dist).is_dir():
        return []
    r = subprocess.run(["grep", "-rlF", "--include=prepare.runtime-*.mjs", "-e", STABLE_EDITS[0][0], str(dist)],
                       capture_output=True, text=True)
    return sorted(r.stdout.split())


def _stable_state(s):
    """'patched', 'original', or why the file can't be patched safely (each anchor must appear exactly once)."""
    if STABLE_MARK in s:
        return "patched" if all(s.count(new) == 1 for _, new in STABLE_EDITS) else "partly patched"
    missing = [old[:60] for old, _ in STABLE_EDITS if s.count(old) != 1]
    return "original" if not missing else f"anchors changed: {missing}"


def _stable_patched(s):
    for old, new in STABLE_EDITS:
        s = s.replace(old, new, 1)
    return s


def patch_stable_prompt(dist, backup_dir=None):
    """Returns (files changed, files holding the code, problems)."""
    files, changed, problems = stable_prompt_files(dist), [], []
    for f in files:
        s = read(f)
        state = _stable_state(s)
        if state == "patched":
            continue
        if state != "original":
            problems.append(f"{os.path.basename(f)}: {state}")
            continue
        new = _stable_patched(s)
        if backup_dir:
            Path(backup_dir).mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, Path(backup_dir) / os.path.basename(f))
        mode = os.stat(f).st_mode
        tmp = f + ".team-tmp"
        Path(tmp).write_text(new)
        os.chmod(tmp, mode)
        os.replace(tmp, f)
        changed.append(f)
    return changed, files, problems


def stable_prompt_check(dist):
    texts = {f: read(f) for f in stable_prompt_files(dist)}
    if not texts:
        return False, "OpenClaw CLI prompt preparation: not found (OpenClaw changed it: the orchestrator may re-cache its conversation on every kind of wake again)"
    bad = {os.path.basename(f): st for f, s in texts.items() if (st := _stable_state(s)) != "patched"}
    return not bad, "OpenClaw system prompt kept the same across wakes" + (f": {bad} (run apply)" if bad else "")


def browser_timeouts_check(dist, ms, attach_ms=0):
    texts = {f: read(f) for f in browser_timeout_files(dist)}
    missing = []
    if not any(f"const {CDP_CONSTS[0]} =" in s for s in texts.values()):
        missing.append("remote browser timeouts")
    if attach_ms and not any(re.search(ATTACH_RE, s) for s in texts.values()):
        missing.append("browser attach timeout")
    if missing:
        return False, f"OpenClaw {' and '.join(missing)}: not found (OpenClaw changed them: the laptop browser may time out again)"
    bad = [os.path.basename(f) for f, s in texts.items() if _browser_patched(s, ms, attach_ms) != s]
    label = f"OpenClaw remote browser timeouts {int(ms)} ms" + (f", attach {int(attach_ms)} ms" if attach_ms else "")
    return not bad, label + (f": reset in {bad} (run apply)" if bad else "")


