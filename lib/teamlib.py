def leak_scan(texts):
    """[(where, what)] for every real private value (and every owner privacy pattern) found in {where: text}.
    Names keys and pattern numbers only, never the values."""
    p = private_file()
    if p is None or p.resolve() == PRIVATE_EXAMPLE.resolve():
        raise SystemExit("leak check needs the REAL private.toml (not private.example.toml)")
    needles = [(k, v) for k, v in private_values().items() if len(v) >= 4]
    pats = []
    if PRIVACY_PATTERNS.exists():
        lines = [x.strip() for x in PRIVACY_PATTERNS.read_text().splitlines()]
        pats = [(i, re.compile(x, re.I)) for i, x in enumerate(lines, 1) if x and not x.startswith("#")]
    out = []
    for where, text in texts.items():
        out += [(where, f"private value {k}") for k, v in needles if v in text]
        if not where.startswith("vendor-skills/"):   # third-party text (photo credits, SVG paths) trips the loose patterns
            out += [(where, f"privacy pattern line {i}") for i, rx in pats if rx.search(text)]
    return out


def tracked_texts(rev=None):
    """{path: text} of the tracked tree (the work tree, or the files at commit rev), names included."""
    r = subprocess.run(["git", "-C", str(REPO), "ls-files"] if rev is None else
                       ["git", "-C", str(REPO), "ls-tree", "-r", "--name-only", rev], capture_output=True, text=True)
    if r.returncode == 0 and (REPO / ".git").exists():
        names = r.stdout.splitlines()
    elif rev is None:   # an exported copy (git archive, the host's checkout): every file but the ignored ones
        skip = {".git", "__pycache__", "build", "private.toml"}
        names = sorted(str(p.relative_to(REPO)) for p in REPO.rglob("*")
                       if p.is_file() and not skip & set(p.relative_to(REPO).parts) and p.suffix != ".pyc")
    else:
        raise SystemExit(f"git ls-tree {rev} failed: {r.stderr.strip()}")
    out = {"(file names)": "\n".join(names)}
    for n in names:
        try:
            out[n] = ((REPO / n).read_text(errors="replace") if rev is None else
                      subprocess.run(["git", "-C", str(REPO), "show", f"{rev}:{n}"], capture_output=True, check=True).stdout.decode(errors="replace"))
        except (OSError, subprocess.CalledProcessError):
            pass
    return out


def cmd_leaks(args):
    """Prove nothing private is in the repo: the tracked files, or with --commits A..B every pushed commit's
    diff and message (author lines are left out: the owner's commit identity may be public)."""
    if args.commits:
        log = subprocess.run(["git", "-C", str(REPO), "log", "-p", "--format=commit %H%n%B", args.commits],
                             capture_output=True, text=True, errors="replace", check=True).stdout
        texts = {}   # one text per file diff (named by its path, so vendor files are judged as vendor files) + messages
        for chunk in re.split(r"(?m)^(?=commit [0-9a-f]{40}$|diff --git )", log):
            m = re.match(r"diff --git a/(.*?) b/", chunk)
            where = m.group(1) if m else f"commit messages {args.commits}"
            texts[where] = texts.get(where, "") + chunk
    else:
        texts = tracked_texts()
    found = leak_scan(texts)
    for where, what in found:
        print(f"LEAK {where}: {what}")
    print(f"leaks: {len(found)} in {len(texts)} texts")
    sys.exit(1 if found else 0)


