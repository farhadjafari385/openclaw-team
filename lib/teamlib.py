def render_files(team, projects):
    """{absolute path: content} for every generated workspace file."""
    ws = expand(team["team"]["workspace_root"])
    owner = read(REPO / "owner.md")
    files = {}
    limit = int(team["limits"]["bootstrap_max_chars"])
    for agent in team["agents"]:
        base = ws / agent["id"]
        text = agents_md(team, projects, agent)
        # 85%: OpenClaw truncates at bootstrap_max_chars; the rest is headroom (2026-11-12: 80% left 44 characters
        # for the orchestrator, and the owner's postmortem rule did not fit).
        if len(text) > int(limit * BOOTSTRAP_SHARE):
            raise SystemExit(f"AGENTS.md for {agent['id']} is {len(text)} chars; keep it under {int(limit * BOOTSTRAP_SHARE)} ({int(BOOTSTRAP_SHARE * 100)}% of bootstrap_max_chars) so nothing is truncated")
        files[str(base / "AGENTS.md")] = text
        files[str(base / "SOUL.md")] = soul_md(agent)
        files[str(base / "IDENTITY.md")] = identity_md(agent)
        files[str(base / "USER.md")] = owner
        for src in sorted(glob.glob(str(REPO / "skills" / agent["id"] / "**" / "*"), recursive=True)):
            if os.path.isfile(src):
                rel = fill(os.path.relpath(src, REPO / "skills" / agent["id"]), src)   # a folder may be named by a placeholder
                files[str(base / "skills" / rel)] = read(src)
    files[str(ws / "AGENTS.md")] = ("# Team workspace\n\n" + GENERATED_NOTE + "\n\nEach agent's rules are in its own folder's AGENTS.md.\n\n"
                                    + read(REPO / "rules" / "core.md").strip() + "\n\n" + team_section(team))
    return files


