# ---------------------------------------------------------------- load

def load():
    team = tomllib.loads(read(REPO / "team.toml"))
    projects = tomllib.loads(read(REPO / "projects.toml")).get("projects", [])
    ids = [a["id"] for a in team["agents"]]
    if len(ids) != len(set(ids)):
        raise SystemExit("team.toml: duplicate agent ids")
    orch = [a for a in team["agents"] if a.get("role") == "orchestrator"]
    if len(orch) != 1:
        raise SystemExit("team.toml: exactly one agent must have role = \"orchestrator\"")
    for a in team["agents"]:
        if not (REPO / "personas" / f"{a['id']}.md").exists():
            raise SystemExit(f"personas/{a['id']}.md is missing")
        if a.get("role") != "orchestrator" and not (REPO / "roles" / f"{a['role']}.md").exists():
            raise SystemExit(f"roles/{a['role']}.md is missing")
    return team, projects


def orchestrator(team):
    return next(a for a in team["agents"] if a.get("role") == "orchestrator")


