def gateway_env():
    env = dict(os.environ)
    env["PATH"] = f"{HOME}/.openclaw/tools/node-v24.21.0/bin:{HOME}/.openclaw/bin:" + env.get("PATH", "")
    envfile = HOME / ".openclaw" / "gateway.systemd.env"
    if envfile.exists():
        for line in envfile.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip().strip('"')
    return env


def run(cmd, timeout=300, check=False):
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, env=gateway_env())
    except subprocess.TimeoutExpired as e:
        r = subprocess.CompletedProcess(cmd, 124, stdout=(e.stdout or b"").decode() if isinstance(e.stdout, bytes) else (e.stdout or ""), stderr=f"timed out after {timeout}s")
    if check and r.returncode != 0:
        raise SystemExit(f"command failed ({r.returncode}): {' '.join(cmd)}\n{r.stderr[-800:]}")
    return r


def merge_patch(target, patch):
    """RFC 7386 merge patch: objects merge, null deletes, everything else replaces."""
    if not isinstance(patch, dict):
        return patch
    out = dict(target) if isinstance(target, dict) else {}
    for k, v in patch.items():
        if v is None:
            out.pop(k, None)
        else:
            out[k] = merge_patch(out.get(k), v)
    return out


def apply_config_patch(team, patch, workdir):
    """Apply a config patch with the OpenClaw CLI; if the CLI refuses because the
    current file no longer validates (e.g. a key the new plugin schema dropped),
    merge it directly and let `openclaw config validate` decide, restoring on failure."""
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, dir=str(workdir)) as f:
        json.dump(patch, f)
    for attempt in range(3):
        r = run([openclaw(team), "config", "patch", "--file", f.name], timeout=300)
        if r.returncode == 0:
            return "patched"
        if "changed since last load" not in (r.stdout + r.stderr):
            break
    out = r.stdout + r.stderr
    if "config is invalid" not in out and "timed out" not in out:
        raise SystemExit(f"config patch failed:\n{out[-800:]}")
    path = expand(team["team"]["openclaw_home"]) / "openclaw.json"
    before = read(path)
    Path(path).write_text(json.dumps(merge_patch(json.loads(before), patch), indent=2) + "\n")
    v = run([openclaw(team), "config", "validate"], timeout=300)
    if v.returncode != 0:
        Path(path).write_text(before)
        raise SystemExit(f"merged config does not validate; restored the previous file:\n{(v.stdout + v.stderr)[-800:]}")
    return "merged and validated (the CLI patch refused or timed out)"


