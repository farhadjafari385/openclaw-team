def guard_loaded():
    """(ok, message): did token-guard load in the current gateway process?"""
    since = subprocess.run(["systemctl", "--user", "show", "openclaw-gateway", "-p", "ActiveEnterTimestamp", "--value"], capture_output=True, text=True).stdout.strip()
    epoch = subprocess.run(["date", "-d", since, "+%s"], capture_output=True, text=True).stdout.strip() if since else ""
    if not epoch.isdigit():
        return (False, f"token-guard: gateway start time unknown ({since or 'not running'})")
    log = subprocess.run(["journalctl", "--user", "-u", "openclaw-gateway", "--since", f"@{epoch}", "--no-pager"], capture_output=True, text=True).stdout
    if re.search(r"token-guard failed during load|plugin failed during load[^\n]*token-guard", log):
        return (False, "token-guard FAILED to load in the running gateway (see journalctl --user -u openclaw-gateway)")
    m = re.search(r"http server listening \(\d+ plugins: ([^)]*)", log)
    if not m:
        return (False, "token-guard: gateway still starting (no 'http server listening' yet)")
    return ("token-guard" in m.group(1), "token-guard loaded" if "token-guard" in m.group(1) else "token-guard NOT in the loaded plugins")


def _flatten(d, prefix=""):
    out = []
    for k, v in d.items():
        key = f"{prefix}.{k}" if prefix else k
        out.extend(_flatten(v, key) if isinstance(v, dict) and v else [key])
    return out


