def model_obj(spec):
    return {"primary": spec["primary"], "fallbacks": list(spec.get("fallbacks", []))}


def mcp_servers(team):
    """mcp.servers for openclaw.json from team.toml ([mcp.servers.<name>]); "~/" in a command or argument is expanded."""
    out = {}
    for name, spec in (team.get("mcp", {}).get("servers") or {}).items():
        d = {"enabled": True}
        if spec.get("url"):
            d.update({"url": spec["url"], "transport": spec.get("transport", "streamable-http")})
        else:
            d.update({"command": str(expand(spec["command"])),
                      "args": [str(expand(a)) if str(a).startswith("~/") else a for a in spec.get("args", [])]})
        out[name] = d
    return out


def agent_tools(team, agent):
    """The agent's tool policy plus a deny rule for every MCP server it is not given."""
    tools = dict(agent.get("tools", {"profile": "full"}))
    mine = set(agent.get("mcp", []))
    deny = [f"{s}__*" for s in sorted(mcp_servers(team)) if s not in mine]
    trim = team.get("tool_trim", {})
    deny += list(trim.get("nobody", []))
    if agent.get("role") != "orchestrator":
        deny += list(trim.get("workers", []))
    if deny:
        tools["deny"] = sorted(set(tools.get("deny", [])) | set(deny))
    return tools


