def projects_section(projects):
    lines = ["## Projects", "", "Name a project in every brief by its name. Topic = its Telegram topic. Work in the server path unless the task needs the laptop.", ""]
    for p in projects:
        where = " · ".join(x for x in [f"server `{p['server']}`" if p.get("server") else "", f"laptop `{p['laptop']}`" if p.get("laptop") else ""] if x)
        aka = f" (also: {', '.join(p['aliases'])})" if p.get("aliases") else ""
        note = f" — {p['notes']}" if p.get("notes") else ""
        lines.append(f"- **{p['name']}**{aka}, topic {p['topic']}: {where or 'no files'}{note}")
    return "\n".join(lines) + "\n"


def team_section(team):
    """Who is who in the Telegram group, from team.toml, so every agent can mention the right person."""
    o = team["owner"]
    lines = ["## The team", "", "Mention people by their handle. Each agent posts from its own bot.", "",
             f"- **Owner:** {o['name']}" + (f", @{o['handle']}" if o.get("handle") else "") + " (decisions and approvals)"]
    for a in team["agents"]:
        who = f"@{a['handle']}" if a.get("handle") else a["id"]
        lines.append(f"- {a['emoji']} **{a['name']}** ({a['id']}): {who}")
    return "\n".join(lines) + "\n"


def agents_md(team, projects, agent):
    persona = read(REPO / "personas" / f"{agent['id']}.md").strip()
    parts = [persona.split("\n", 1)[0], "", GENERATED_NOTE, "", persona.split("\n", 1)[1].strip(), "", read(REPO / "rules" / "core.md").strip(), "",
             team_section(team).strip(), ""]
    if agent.get("role") == "orchestrator":
        parts += [read(REPO / "rules" / "orchestrator.md").strip(), ""]
    else:
        parts += [read(REPO / "roles" / f"{agent['role']}.md").strip(), "", read(REPO / "rules" / "worker.md").strip(), ""]
    parts += [projects_section(projects).strip(), "", read(REPO / "facts.md").strip(), ""]
    return "\n".join(parts)


