def skill_frontmatter(path):
    """(name, description) from a SKILL.md frontmatter (plain, quoted or folded description)."""
    try:
        text = Path(path).read_text(errors="replace")
    except OSError:
        return None, ""
    if is_team_file(path):
        text = fill(text, path)
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    if not m:
        return None, ""
    lines = m.group(1).split("\n")
    name, desc = None, ""
    for i, line in enumerate(lines):
        if line.startswith("name:"):
            name = line.split(":", 1)[1].strip().strip("'\"")
        if line.startswith("description:"):
            v = line.split(":", 1)[1].strip()
            if v in (">", ">-", "|", "|-", ""):
                v = " ".join(x.strip() for x in lines[i + 1:] if x.startswith((" ", "\t")) and x.strip())
                # stop at the next top-level key
                block = []
                for x in lines[i + 1:]:
                    if x and not x.startswith((" ", "\t")):
                        break
                    block.append(x.strip())
                v = " ".join(b for b in block if b)
            desc = v.strip().strip("'\"")
    return name, desc


def skill_catalog(team):
    """{agent id: [{name, about, always}]} for the guard: each agent's allowed skills with their own descriptions."""
    found = {}
    for p in (REPO / "vendor-skills").glob("*/SKILL.md"):
        n, d = skill_frontmatter(p)
        found[n or p.parent.name] = d
    for p in (REPO / "skills").glob("*/*/SKILL.md"):
        n, d = skill_frontmatter(p)
        found.setdefault(n or fill(p.parent.name, p), d)
    home =expand(team["team"]["openclaw_home"])
    for root in [home / "plugin-skills", *sorted((home / "tools").glob("node-*/lib/node_modules/openclaw/skills"))]:
        for p in root.glob("*/SKILL.md") if root.is_dir() else []:
            n, d = skill_frontmatter(p)
            found.setdefault(n or p.parent.name, d)
    out = {}
    for a in team["agents"]:
        out[a["id"]] = [{"name": s, "about": found.get(s, "")[:1200],
                         "always": s.endswith("-playbook") or s == "verification-before-completion"}
                        for s in a.get("skills", [])]
    return out


